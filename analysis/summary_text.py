"""Renders results/RESULTS_SUMMARY.md from the assembled results dictionary."""

from __future__ import annotations


def table(header: list[str], rows: list[list]) -> str:
    out = ["", "| " + " | ".join(header) + " |", "|" + "|".join("---" for _ in header) + "|"]
    out += ["| " + " | ".join(str(c) for c in r) + " |" for r in rows]
    return "\n".join(out)


def render(R: dict, dev: list[dict], f) -> str:
    M, S, D, CO = R["meta"], R["sec_res_structure"], R["sec_res_diffusion"], R["sec_res_collab"]
    rob, HP = R["robustness"], R["human_platform"]
    L = []
    a = L.append
    a("# MoltBook re-analysis: results summary\n")
    a("Generated by `analysis/s11_assemble.py` from `results/results.json`. Re-create everything with `analysis/run_all.sh`. "
      "All random seeds are 42.\n")

    a("## Data\n")
    a(f"- Primary data: archive revision `{M['primary_revision'][:8]}`, the revision pinned by the repo's "
      f"`moltbook-observatory-archive` gitlink and used by the earlier run. Window {M['window'][0]} to {M['window'][1]} (UTC): "
      f"{f(M['posts'])} posts, {f(M['comments'])} comments, {f(M['agents'])} agents in the agents table "
      f"({f(M['active_agents'])} active in the window).")
    cov = M["coverage"]
    a(f"- The current archive head (`{M['head_revision'][:8]}`) has back-filled posts ({f(cov['head_window_posts'])} in the window), but only "
      f"{100 * cov['primary_window_comments_present_in_head']:.1f}% of the pinned revision's window comments are still present, so it was not used as primary. "
      "Row counts and hashes of both are in `results/data_manifest.json`.")
    a(f"- Interaction graph: {f(M['graph_nodes'])} nodes, {f(M['graph_edges'])} edges, {f(M['graph_interactions'])} interactions. "
      f"In the pinned revision only {100 * cov['primary_top_level_comments_with_post_in_primary']:.1f}% of top-level comments point to a post present in it; "
      "the rest produce no edge. The `merged` variant (pinned revision plus head, deduplicated by id) raises this to "
      f"{100 * cov['primary_top_level_comments_with_post_in_primary_or_head_window']:.1f}% and is reported as a sensitivity check.\n")

    a("## Reference values versus rerun\n")
    a(table(["Quantity", "Reference", "Rerun", "Deviation", "Cause / note"],
            [[d["quantity"], d["reference"], f(d["rerun"], 4) if isinstance(d["rerun"], float) else f(d["rerun"]),
              f"{d['deviation_pct']:+.1f}%", d["cause"]] for d in dev]))
    a("")

    a("## 1. Population structure (step 2)\n")
    sweep_txt = ", ".join("k=%d: %.3f" % (r["k"], r["silhouette"]) for r in S["k_sweep"])
    a(f"- k-means over k=3..8 on five standardized features (in/out-degree, exact betweenness, clustering, PageRank). "
      f"Max-silhouette k = **{S['selected_k']}**, silhouette **{f(S['silhouette'])}**; at k=6 the silhouette is {f(S['silhouette_at_k6'])}. "
      f"The curve is flat ({sweep_txt}).")
    b = S["bootstrap"]
    a(f"- Bootstrap (100 resamples): ARI vs reference mean {f(b['ari']['mean'])} (95% {f(b['ari']['ci_lower'])}-{f(b['ari']['ci_upper'])}), "
      f"silhouette mean {f(b['silhouette']['mean'])} ({f(b['silhouette']['ci_lower'])}-{f(b['silhouette']['ci_upper'])}).")
    a(f"- Largest cluster holds {100 * S['largest_cluster_share']:.1f}% of agents. {100 * S['share_agents_not_in_graph']:.1f}% of agents have no "
      f"interaction at all and share one identical feature vector; {100 * S['periphery_share_total_degree_le_1']:.1f}% have total degree <= 1. "
      "The high silhouette therefore measures how far this inactive mass sits from a few active agents. It does not show separated roles among active agents.")
    g = S["gmm"]
    a(f"- GMM (k={g['k']}): silhouette {f(g['silhouette'])}, ARI vs k-means {f(g['ari_vs_kmeans'])}, mean max posterior {f(g['mean_max_posterior'])} "
      f"({100 * g['share_max_posterior_below_0.9']:.1f}% of agents below 0.9). BIC selects k={g['bic_selected_k']}. Soft assignments are nearly hard, "
      "so GMM does not describe the roles better; the two partitions agree only moderately.")
    a("- Behavioral roles use the code's rules (`results/role_thresholds.json`):")
    a(table(["Role", "Count", "Proportion", "Definition"], [[r["role"], f(r["count"]), f(r["proportion"]), r["definition"]] for r in R["tab_role_taxonomy_results"]]))
    a("  The code's role names (Specialist, Connector, Initiator, Synthesizer, Generalist) differ from the paper's "
      "(Generalist, Initiator, Amplifier, Synthesizer, Curator). Amplifier and Curator are not implemented anywhere.\n")

    a("## 2. Cascades (step 3)\n")
    cc = D["cascade_counts"]
    cap = cc["cap"]
    a(f"- **Cap status: confirmed.** `rq2_diffusion.py` sorts meme cascades by size and keeps `cascades[:10000]`. With the code's defaults "
      f"(n=3..5, >= 10 distinct adopters) there are **{f(cap['uncapped_meme_cascades_n3to5'])}** meme cascades, so the reported 10,000 is the cap. "
      f"The smallest capped cascade has {cap['min_size_in_capped_set_n3to5']} adopters. The earlier run used n=3..5 (function default), not the n=2..5 in the paper/config.")
    a(f"- Uncapped, n=2..5: **{f(cap['uncapped_meme_cascades_n2to5'])}** meme cascades, plus {cc['n_skill']} skill and {cc['n_behavioral']} behavioral "
      f"(total {f(cc['primary_total_uncapped_n2to5'])}). Distinct n-grams by threshold: "
      + "; ".join(f"n={n}: >=2 {f(v['>=2'])}, >=5 {f(v['>=5'])}, >=10 {f(v['>=10'])}" for n, v in cc["ngram_counts_by_n"].items()) + ".")
    a("- The paper's definition (>= 2 agents) yields millions of cascades dominated by common phrases. The >= 10 adopter rule of the code is kept for every fit.")
    a("- Cascade type comes from the extraction method (n-gram = meme, code block = skill, formatting regex = behavioral), "
      "not from keyword classification of the seed post's submolt as the paper states.")
    E = D["embedding_cascades"]
    if "selected" in E:
        a(f"- Embedding cascades (all-MiniLM-L6-v2, FAISS kNN, connected components at cosine >= tau): tau = {E['calibration']['selected_tau']} chosen on "
          f"a held-out calibration sample (F1 {f(E['calibration']['at_tau']['f1'])}; test F1 {f(E['test']['at_tau']['f1'])}, "
          f"precision {f(E['test']['at_tau']['precision'])}, recall {f(E['test']['at_tau']['recall'])}). "
          f"{f(E['selected']['n_cascades'])} cascades with >= 10 adopters (largest component holds "
          f"{100 * E['selected']['largest_component_item_share']:.1f}% of items). tau +/- 0.05: "
          + ", ".join(f"tau={k}: {f(v['n_cascades'])}" for k, v in E["tau_sensitivity"].items()) + ".")
    else:
        a("- Embedding cascades: not available (see open issues).")
    a("")

    a("## 3. Power law (step 5)\n")
    rows = []
    for name, p in R["app_powerlaw"]["fits"].items():
        rows.append([name, f(p["n"]), f(p["alpha"]), f"{f(p['alpha_ci95'][0])}-{f(p['alpha_ci95'][1])}", f(p["xmin"], 0), f(p["ks_D"], 4),
                     f"{f(p['vs_exponential']['normalized_llr'], 2)} ({p['vs_exponential']['favors']})",
                     f"{f(p['vs_lognormal']['normalized_llr'], 2)} ({p['vs_lognormal']['favors']})",
                     f"{f(p['vs_truncated_power_law']['normalized_llr'], 2)} ({p['vs_truncated_power_law']['favors']})",
                     f(p["goodness_of_fit"]["gof_p"]) if "goodness_of_fit" in p else "not run"])
    a(table(["Set", "n", "alpha", "95% CI", "xmin", "KS D", "LR vs exp", "LR vs lognormal", "LR vs trunc. PL", "GOF p"], rows))
    a("\nLR = normalized log-likelihood ratio (positive favors the power law); the favored model is shown when p < 0.05. "
      "Sizes are in `results/cascades.csv`, CCDF and fitted curves in `results/figure2_ccdf.csv`.")
    rp = D["powerlaw_reproduction_capped"]
    a(f"- The capped reproduction set gives alpha = {f(rp['alpha'])} with xmin = {f(rp['xmin'], 0)}, essentially the cap boundary. "
      "The earlier fit described the cap-truncated top of the distribution. The uncapped fits describe the actual distribution.\n")

    a("## 4. Exposure and adoption (step 4)\n")
    a("- Exact definition: `results/exposure_definition.md`. An exposure is one distinct in-neighbour in the static reply graph "
      "(an agent that commented on or replied to the focal agent) that used the cascade. Adopters count only neighbours who adopted strictly earlier; "
      "non-adopters count all adopting neighbours over the whole window. Repeated use by the same neighbour counts once.")
    rows = []
    for name, lg in D["logistic"].items():
        for pred in ("exposure", "exposure_squared"):
            c = lg["coefficients"][pred]
            rows.append([name, pred, f(c["coef"], 5), f(c["se_cluster_cascade"], 5), f(c["se_model_based"], 5), f(c["p"])])
    a(table(["Logistic model", "Term", "Coef", "SE (cluster by cascade)", "SE (model)", "p"], rows))
    pr = D["logistic"]["primary_uncapped_n2to5"]
    a(f"\n- Primary logistic: {f(pr['n_observations'])} agent x cascade observations, {f(pr['n_clusters_cascades'])} cascade clusters; "
      f"{pr['curvature']}, vertex at {f(pr['vertex_exposure'], 1)} exposures. Binned rates with Wilson intervals are in `results/figure3_binned_adoption.csv`.")
    rows = []
    for name, c in D["cox"].items():
        sch = c.get("schoenfeld_test", {})
        rows.append([name, f(c["hazard_ratio"]), f"{f(c['hr_ci95'][0])}-{f(c['hr_ci95'][1])}", f(c["p"]), f(c["n_events"]), c["se_type"],
                     f(sch["p"]) if sch else "n/a for time-varying"])
    a(table(["Cox model", "HR", "95% CI", "p", "events", "SE", "Schoenfeld p"], rows))
    a("\n- **Frailty:** neither lifelines nor statsmodels implements a shared-frailty Cox model, so the stratified-by-cascade model "
      "(cascade-specific baseline hazards) stands in for it. "
      f"With time-varying cumulative exposure (the paper's stated model), HR = {f(D['cox']['random100_timevarying_stratified']['hazard_ratio'])} stratified and "
      f"{f(D['cox']['random100_timevarying_pooled']['hazard_ratio'])} pooled: each additional exposed neighbour **raises** the adoption hazard. "
      f"The earlier HR < 1 comes from the static, asymmetric exposure count. It reappears in the static models "
      f"(top-100 reproduction {f(D['cox']['reproduction_top100_static']['hazard_ratio'])}; random-100 static {f(D['cox']['random100_static_pooled_clustered']['hazard_ratio'])}). "
      "The earlier run also used the 100 largest cascades rather than a random sample.\n")

    a("## 5. Collaboration (step 6)\n")
    a(f"- {f(CO['n_events'])} collaborative events among {f(CO['n_technical_threads'])} technical threads (posts in the window with a keyword in title/body).")
    a(f"- **Paired vs two-sample in the code:** {CO['comparison_type_in_code']}.")
    e = CO["earlier_run_test_Q_code"]
    a(f"- Reproduction of the earlier number: Q_code mean {f(e['mean'])} (SD {f(e['sd'])}), t = {f(e['t'], 2)}, d = {f(e['cohens_d'], 3)} against the constant 0.5. "
      "This d compares Q with an arbitrary constant, not with any baseline.")
    a("- Q as implemented (Q_code: code .30, '#|//' comments .20, test words .30, balanced brackets .20) differs from the paper's Q "
      "(Q_spec: code .30, comment quality .30, tests .20, ast syntax .20). Both are reported; Q_spec is primary. Its comment-quality "
      "operationalisation (mean of rescaled VADER compound and min(1, words/50)) is defined in this rerun.")
    for q in ("Q_spec", "Q_code"):
        bl = CO[f"baseline_{q}"]
        rows = []
        for name, v in bl.items():
            if v["available"]:
                rows.append([name, f(v["n_events_matched"]), f(v["n_unique_baseline_threads"]), f(v["baseline_mean_Q"]), f(v["baseline_sd_Q"]),
                             f(v["baseline_success_rate"]), f(v["event_mean_Q"]), f(v["paired"]["t"], 2), f(v["paired"]["p"]),
                             f(v["paired"]["cohens_dz"], 3), f(v["two_sample"]["cohens_d_pooled"], 3)])
            else:
                rows.append([name, f(v["n_events_matched"]), f(v["n_unique_baseline_threads"]), "not estimable", "", "", "", "", "", "", ""])
        a(f"\n**{q}** matched baselines (up to 5 matches per event; paired t-test on event-level differences):\n")
        a(table(["Baseline", "events matched", "baseline threads", "baseline mean", "baseline SD", "baseline success", "event mean",
                 "paired t", "p", "d_z", "two-sample d"], rows))
    a("\n- Baseline mean, SD and success rate are over the unique matched threads. The paired test uses each event's own mean of its "
      "matches, so threads reused across many events weigh more there; this is why the paired d_z and the two-sample d can differ in sign.")
    pb = CO["baseline_Q_spec"]["paper_baseline_single_agent"]
    if pb["available"]:
        a(f"\n- The paper's single-agent baseline is estimable ({pb['n_events_matched']} events matched to {pb['n_unique_baseline_threads']} threads).")
    else:
        a(f"\n- The paper's single-agent baseline is not estimable on the pinned revision: only {CO['n_single_agent_technical_threads']} single-agent "
          f"technical threads exist, and the {pb['n_events_matched']} events that find a match all match the same {pb['n_unique_baseline_threads']} thread(s). "
          "The primary baseline uses technical non-event threads with 1-2 participants. On the merged data the single-agent baseline is estimable (section 9).")
    dr = CO["dose_response"]
    a(f"- Dose-response (OLS, HC3): Q_spec on log participants across events: slope {f(dr['Q_spec']['events']['slope'])} (p {f(dr['Q_spec']['events']['p'])}, n {dr['Q_spec']['events']['n']}); "
      f"Q_code: {f(dr['Q_code']['events']['slope'])} (p {f(dr['Q_code']['events']['p'])}). Across all technical threads with >= 5 comments: "
      f"Q_spec {f(dr['Q_spec']['all_technical_threads_ge5_comments']['slope'])} (n {f(dr['Q_spec']['all_technical_threads_ge5_comments']['n'])}), "
      f"Q_code {f(dr['Q_code']['all_technical_threads_ge5_comments']['slope'])}.")
    a(table(["Q", "Component", "Weight", "Successful", "Unsuccessful"],
            [[c["q"], c["component"], c["weight"], f(c["successful_mean"]), f(c["unsuccessful_mean"])] for c in R["tab_quality_components"]]))
    a("")

    QV = R["app_task3"]["q_validation"]
    ws = QV["weight_sensitivity"]
    a("## 6. Q validation (step 7)\n")
    a(f"- Rating sheet `results/q_validation_sample.csv`: {QV['sample']['n_sampled']} events stratified by Q_spec quintile, blinded, with an empty "
      f"`human_score` column; the key is in `results/q_validation_key.csv`. Agreement statistics are computed once ratings exist ({QV['sample']['n_rated']} rated now).")
    for q in ("Q_spec", "Q_code"):
        w = ws[q]
        a(f"- {q} under 20 random simplex weights: Spearman with original median {f(w['spearman_median'])} (min {f(w['spearman_min'])}); "
          f"success rate ranges {f(w['success_rate_range'][0])}-{f(w['success_rate_range'][1])} (original {f(w['original_success_rate'])}), "
          f"median share of events changing success status {f(w['success_flip_share_median'])}.")
    a(f"- Spearman(Q_spec, Q_code) across events: {f(QV['q_spec_vs_q_code_spearman'])}.\n")

    AU = rob["autonomy_audit"]
    a("## 7. Autonomy audit (step 8)\n")
    a(f"- Rules: R1 cadence (>= 30 events over >= 2 days with a >= 6 h daily gap in UTC hour-of-day), R2 duplicated text (>= 50% of >= 5 items are "
      f"verbatim self-copies), R3 burstiness (B >= 0.5 over >= 10 events). Flagged {f(AU['n_flagged'])} of {f(AU['scored_agents'])} active agents "
      f"({100 * AU['share_of_active_agents_flagged']:.1f}%): R1 {AU['flag_counts']['R1_cadence']}, R2 {AU['flag_counts']['R2_duplicates']}, "
      f"R3 {AU['flag_counts']['R3_burstiness']}. They wrote {100 * AU['share_of_items_by_flagged']:.1f}% of all items and "
      f"{100 * AU['share_of_comments_by_flagged']:.1f}% of comments. The flagged set is `results/autonomy_flagged_agents.csv`.")
    a(compare_block(rob["main"], AU["rerun"], "no_autonomy", f))
    a("## 8. Jan 31 incident sensitivity (step 9)\n")
    a("- All posts and comments created 2026-01-30 through 2026-02-01 (UTC) removed; steps 2, 4 and 6 rerun (cascades re-extracted).")
    a(compare_block(rob["main"], rob["incident_sensitivity"]["rerun"], "no_incident", f))
    a("## 9. Merged-data sensitivity\n")
    a(compare_block(rob["main"], rob["merged_data"]["rerun"], "merged", f))

    a("## 10. Human-platform comparison (step 10)\n")
    if "comparison" in HP:
        ds, cm = HP["dataset"], HP["comparison"]
        a(f"- r/programming comments from `{ds['repo']}` ({ds['window_start'][:10]} to {ds['window_end_exclusive'][:10]}, {ds['n_days']} days): "
          f"{f(ds['n_comments'])} comments, {f(ds['n_authors'])} authors. {ds['selection']}.")
        a(table(["Platform", "selected k", "silhouette", "periphery share (lowest cluster)", "periphery share (degree <= 1)", "alpha (n=2..5)", "alpha (n=3..5)"],
                [["MoltBook", cm["moltbook_main"]["selected_k"], f(cm["moltbook_main"]["silhouette"]), f(cm["moltbook_main"]["periphery_share_lowest_cluster"]),
                  f(cm["moltbook_main"]["periphery_share_total_degree_le_1"]), f(cm["moltbook_main"]["alpha_primary_n2to5"]), f(cm["moltbook_main"]["alpha_uncapped_n3to5"])],
                 ["r/programming", cm["reddit_programming"]["selected_k"], f(cm["reddit_programming"]["silhouette"]),
                  f(cm["reddit_programming"]["periphery_share_lowest_cluster"]), f(cm["reddit_programming"]["periphery_share_total_degree_le_1"]),
                  f(cm["reddit_programming"]["alpha_n2to5"]), f(cm["reddit_programming"]["alpha_n3to5"])]]))
        a(f"\n- Caveat: {cm['caveat']}.\n")
    else:
        a("- Not available (see open issues).\n")

    a("## Open issues\n")
    issues = [
        "Primary data choice: the pinned revision reproduces the earlier run, but its graph drops most top-level comments because their posts are missing from it (see Data). "
        "The merged variant fixes this and changes the structural numbers (section 9). The authors should decide which to report as primary.",
        "Q definition: the code's Q differs from the paper's in weights and components; Q_spec's comment-quality formula is defined in this rerun and needs sign-off.",
        "The paper's single-agent matched baseline is not estimable on the pinned revision (estimable on the merged data); a low-participation baseline is primary, and the Methods text must say which is used.",
        "Human ratings for Q validation are pending (`results/q_validation_sample.csv`). Agreement statistics will be added by rerunning step 7.",
        "Shared-frailty Cox is not available in the Python stack; the stratified Cox stands in for it. A gamma-frailty fit (e.g. R coxme) would need a different toolchain.",
        "The exposure definition in the code is asymmetric between adopters and non-adopters and uses a static, whole-window graph; "
        "the logistic and static-Cox results inherit that bias, and only the time-varying Cox avoids it.",
        "Role taxonomy names in the paper (Amplifier, Curator) have no implementation; the code's rules use different role names.",
        "Silhouette-based k selection is not identifiable here (flat curve, maximum at the edge of the range).",
        "The autonomy rules are heuristics without ground truth. R2 (verbatim self-duplication) flags heavy comment spammers, who write most comments.",
        "The earlier run did not apply the 2026-01-28..2026-02-20 window to posts (it included posts up to 2026-02-24).",
        "Embedding-cascade threshold is calibrated against a lexical near-duplicate proxy, not human judgements.",
        "Cascade extraction, exposure models and power law were not rerun on the merged variant (memory: about 2.6M items).",
    ]
    for i in issues:
        a(f"- {i}")
    a("")
    return "\n".join(L)


def compare_block(main: dict, var: dict, name: str, f) -> str:
    rows = []
    for sec in ("structure", "cascades", "exposure", "collaboration"):
        if sec not in var or sec not in main:
            continue
        for k, v in var[sec].items():
            m = main[sec].get(k, "not estimable")
            if isinstance(v, bool):
                continue
            rows.append([f"{sec}.{k}", f(m) if isinstance(m, (int, float)) else m, f(v) if isinstance(v, (int, float)) else v])
    if not rows:
        return f"- `{name}` rerun not available.\n"
    from summary_text import table as t
    return t(["Quantity", "main", name], rows) + "\n"
